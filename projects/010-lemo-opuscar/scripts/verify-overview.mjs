import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const packagePath=process.env.LEMO_PLAYWRIGHT_PATH;
const { chromium }=packagePath?await import(pathToFileURL(path.join(packagePath,'index.mjs')).href):await import('playwright');
const url=process.env.LEMO_PREVIEW_URL||'http://127.0.0.1:4320/1009_codex_project/010-lemo-opuscar/';
const report={date:'2026-10-10',url,checks:[],widths:[],errors:[],localFailures:[],media:{}};
const browser=await chromium.launch({headless:true});
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce',acceptDownloads:true});
  // 验证总览与代码效果不依赖远端；完整有声视频另行记录。
  await context.route('**/*',route=>new URL(route.request().url()).origin===new URL(url).origin?route.continue():route.abort());
  const page=await context.newPage();page.on('pageerror',e=>report.errors.push(e.message));
  page.on('response',r=>{if(r.url().startsWith(url)&&r.status()>=400)report.localFailures.push(r.url());});
  await page.goto(url+'#overview',{waitUntil:'domcontentloaded'});
  await page.locator('.interactive-summary > summary').click();
  await page.waitForSelector('.om-style-names button');
  const {styles}=JSON.parse(await fs.readFile(path.join(root,'web/data/catalog.json'),'utf8'));
  assert.equal(await page.locator('.om-categories article').count(),9);
  assert.deepEqual(await page.locator('.om-style-names button').allTextContents(),styles.map(s=>s.cn));
  for(const [selector,count] of [['.om-flow li',5],['.om-examples article',3],['.om-controls-grid article',6],['.om-scenarios article',6],['.om-values article',4],['.om-delivery li',5]])assert.equal(await page.locator(selector).count(),count);
  report.checks.push('单图完整呈现5步创作链路、9类43种风格、6项约束、6类场景、4项价值和5步交付');
  await page.locator('.om-style-names [data-play="blueprint"]').click();await page.waitForSelector('#film-dialog[open]');
  assert.match(await page.locator('#film-dialog').innerText(),/Blueprint|蓝图/);await page.locator('#close-dialog').click();
  report.checks.push('总览内风格按钮复用真实风格说明入口');
  const frame=page.frameLocator('#overview-blueprint');
  await page.locator('#overview-blueprint').scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>!document.getElementById('overview-toggle').disabled);
  let state=await frame.locator('body').evaluate(()=>window.previewState);
  assert(state.ready&&!state.running,'减少动画偏好下本地画面不自动播放');
  report.checks.push('减少动画偏好下保持静止画面');
  await page.locator('[data-overview-time="11"]').click();
  await page.waitForFunction(()=>document.getElementById('overview-toggle').textContent.includes('暂停'));
  await page.waitForTimeout(650);const one=await frame.locator('#c').screenshot();
  const playing=await frame.locator('body').evaluate(()=>window.previewState);assert(playing.running&&playing.time>11);
  await page.locator('#overview-toggle').click();await page.waitForTimeout(200);
  const paused=await frame.locator('body').evaluate(()=>window.previewState);await page.waitForTimeout(450);
  const still=await frame.locator('body').evaluate(()=>window.previewState);assert(!still.running);assert.equal(still.time,paused.time);
  await page.locator('[data-overview-time="20"]').click();await page.waitForTimeout(650);
  const two=await frame.locator('#c').screenshot();assert.notEqual(createHash('sha256').update(one).digest('hex'),createHash('sha256').update(two).digest('hex'));
  report.media.localBlueprint={playing,paused,jumped:await frame.locator('body').evaluate(()=>window.previewState),differentFrames:true,externalNetworkBlocked:true};
  await page.locator('#overview-toggle').click();
  report.checks.push('断网下原作画面运行、暂停时间不变、11秒与20秒阶段实际画面不同');
  await page.evaluate(async()=>{await Promise.all([...document.querySelectorAll('#overview-map img')].map(img=>{img.loading='eager';return img.decode().catch(()=>{});}));});
  // 图中动画快照 + 整体结构的真实网页截图。
  await page.addStyleTag({content:'.topbar{visibility:hidden!important}'});
  await page.locator('#overview-map').screenshot({path:path.join(root,'assets/overview-page.png')});
  await page.addStyleTag({content:'.topbar{visibility:visible!important}'});
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#overview-download-png').click()]);
  await download.saveAs(path.join(root,'assets/overview-export-check.png'));
  const png=await fs.readFile(path.join(root,'assets/overview-export-check.png'));
  assert.equal(png.readUInt32BE(16),1600);assert(png.readUInt32BE(20)>3500);
  report.export={width:png.readUInt32BE(16),height:png.readUInt32BE(20),bytes:png.length};
  assert.match(await page.locator('#overview-export-status').textContent(),/已生成/);
  const svg=await fs.readFile(path.join(root,'web/dist/lemo-opuscar-overview.svg'),'utf8');
  await fs.writeFile(path.join(root,'assets/overview-export-check.svg'),svg);
  for(const style of styles)assert(svg.includes(style.cn),'导出图包含 '+style.cn);
  assert(!/<(?:script|foreignObject)\b/.test(svg));assert(!/href="https?:/.test(svg),'图片资源全部内嵌');
  report.checks.push('PNG真实下载1600px宽完整图，SVG包含全部43种风格且作品图片内嵌，可离线保存');
  for(const width of [1440,1120,900,390]){
    await page.setViewportSize({width,height:1000});await page.waitForTimeout(180);
    const dims=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth,map:document.getElementById('overview-map').getBoundingClientRect().width}));
    assert(dims.document<=width,`宽度${width}不应横向溢出`);report.widths.push({width,...dims});
  }
  await page.evaluate(()=>scrollTo({top:document.getElementById('overview').offsetTop-145,behavior:'instant'}));
  await page.screenshot({path:path.join(root,'assets/overview-mobile.png')});
  await page.locator('.om-trial [data-preset="pump"]').click();
  assert.equal(await page.locator('#brief-style').inputValue(),'blueprint');assert.match(await page.locator('#brief-topic').inputValue(),/离心泵/);
  report.checks.push('图末端首个试验按钮填写离心泵任务与蓝图风格');
  assert.deepEqual(report.errors,[]);assert.deepEqual(report.localFailures,[]);
  const svgPage=await context.newPage();await svgPage.setViewportSize({width:1600,height:1000});await svgPage.goto(url+'lemo-opuscar-overview.svg');
  const outside=await svgPage.locator('svg text').evaluateAll(nodes=>nodes.map(n=>({text:n.textContent,box:n.getBBox()})).filter(({box})=>box.x<0||box.x+box.width>1600));
  assert.deepEqual(outside,[]);report.checks.push('SVG所有文字均处于画布宽度以内');
  await fs.writeFile(path.join(root,'assets/overview-verification.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report,null,2));
} finally {await browser.close();}
