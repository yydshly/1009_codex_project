const { chromium } = require(process.argv[2] || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { createHash } = require('node:crypto');
const url = process.argv[3] || 'http://127.0.0.1:4519/';
const project = path.resolve(__dirname, '../..');
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', response => { if (response.status() >= 400) errors.push(response.status() + ' ' + response.url()); });
  const response = await page.goto(url);
  assert.equal(response.status(), 200);
  await page.evaluate(() => document.fonts.ready);
  await page.locator('.guide-figure img').evaluate(img => img.decode());
  assert.match(await page.title(), /LibTV Skills/);
  assert.equal(await page.locator('.reading-content > section').count(), 11);
  assert.equal(await page.locator('#guide img').evaluate(img => img.naturalWidth), 2400);
  await page.screenshot({ path: path.join(project, 'assets/desktop-preview.png') });
  await page.locator('#tab-creation').click();
  assert.equal(await page.locator('#panel-creation').isVisible(), true);
  assert.equal(await page.locator('#panel-service').isVisible(), false);
  await page.locator('#tab-creation').press('ArrowLeft');
  assert.equal(await page.locator('#tab-service').getAttribute('aria-selected'), 'true');
  assert.equal(await page.locator('#panel-service').isVisible(), true);
  const closedModule = page.locator('.module-list details').nth(2);
  await closedModule.locator('summary').click();
  assert.equal(await closedModule.getAttribute('open'), '');
  await page.locator('.hero-copy [data-open-guide]').click();
  assert.equal(await page.locator('#guide-dialog').isVisible(), true);
  await page.locator('#guide-size').click();
  assert.equal(await page.locator('#guide-size').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#guide-dialog img').evaluate(img => Math.round(img.getBoundingClientRect().width)), 2400);
  const downloadPromise = page.waitForEvent('download');
  await page.locator('.dialog-bar a[download]').click();
  const download = await downloadPromise;
  const downloadedBytes = await fs.readFile(await download.path());
  assert.equal(createHash('sha256').update(downloadedBytes).digest('hex'), '9a5f3d7c7150d130871e5a3b870c72493fda773159014e290778faab078938c9');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#guide-dialog').isVisible(), false);
  assert.equal(await page.locator('.hero-copy [data-open-guide]').evaluate(el => el === document.activeElement), true);
  const notesPromise = page.waitForEvent('download');
  await page.locator('#evidence a[href="./research.md"]').click();
  const notes = await notesPromise;
  assert.match(await fs.readFile(await notes.path(), 'utf8'), /直接复用价值有限/);
  await page.locator('#value').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(project, 'assets/value-preview.png') });
  const sizes = [];
  for (const width of [390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.goto(url);
    await page.locator('.guide-figure img').evaluate(img => img.decode());
    const size = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }));
    assert.ok(size.document <= size.viewport, '横向溢出：' + JSON.stringify(size));
    sizes.push(size);
    if (width === 390) await page.screenshot({ path: path.join(project, 'assets/mobile-preview.png') });
  }
  assert.deepEqual(errors, []);
  const noJs = await browser.newPage({ javaScriptEnabled: false, viewport: { width: 390, height: 900 } });
  await noJs.goto(url);
  assert.equal(await noJs.locator('#panel-creation').isVisible(), true);
  assert.equal(await noJs.locator('#panel-service').isVisible(), true);
  assert.equal(await noJs.locator('#guide a').first().getAttribute('href'), './assets/libtv-summary.png');
  await browser.close();
  console.log(JSON.stringify({ result: 'passed', url, sections: 11, errors, sizes, interactions: ['流程点击／键盘', '模块展开', '原图窗口／原始尺寸／Escape／焦点恢复', '原 PNG 下载与哈希', '研究记录下载', '无 JS 可读'] }));
})().catch(error => { console.error(error); process.exit(1); });
