import assert from 'node:assert/strict';
import {cleanNavigation,cleanWorkspace,cleanMemory,appendObservation,observationLimit} from '../public/exploration-memory.js';
const view={version:1,scene:'market',camera:[1,2,3],target:[0,0,0],parameters:{route:20},lived:{settings:{exchange:'cloth'},clock:0},navigation:{recursive:'excluded'}};
const nav={version:3,stage:'model',eventId:'zhang',placeId:'kashgar',modelId:'market',progress:.74,modelLinked:false,modelBookmark:{...view,scene:'terrain'}};
let memory=cleanMemory(null);
memory=appendObservation(memory,nav,view,'first','搬运中');
assert.equal(memory.observations.length,1);
const moved={...view,camera:[3,4,5]};
memory=appendObservation(memory,nav,moved,'replacement','搬运中');
assert.equal(memory.observations.length,1,'same observation updates its viewpoint instead of duplicating assets or rows');
assert.deepEqual(memory.observations[0].workspace.camera,[3,4,5]);
assert.equal(memory.observations[0].workspace.navigation,undefined,'recursive navigation is removed');
for(let i=0;i<20;i++)memory=appendObservation(memory,{...nav,progress:i/20},view,'o'+i);
assert.equal(memory.observations.length,observationLimit);
assert.equal(cleanMemory(JSON.parse(JSON.stringify(memory))).observations.length,observationLimit);
assert.equal(cleanMemory({observations:[{navigation:nav,workspace:{...view,scene:'people'}}]}).observations.length,0,'mismatched event model is rejected');
assert.equal(cleanWorkspace({...view,camera:[Infinity,0,0]}).camera,undefined);
assert.equal(cleanWorkspace({...view,scene:'unknown'}),null);
assert.equal(cleanWorkspace({...view,parameters:{retreat:200,flow:'invalid'}}).parameters.retreat,100);
assert.equal(cleanWorkspace({...view,parameters:{retreat:200,flow:'invalid'}}).parameters.flow,undefined);
assert.equal(cleanNavigation({...nav,modelId:'people'}).stage,'place','ineligible historical models fall back to their place');
assert.equal(cleanNavigation({...nav,placeId:'missing'}).stage,'event');
assert.equal(cleanNavigation({version:2,stage:'model',landform:'glacier',modelId:'glacier',progress:1}).landform,'glacier');
assert.equal(cleanNavigation({version:1,stage:'model',eventId:'protectorate',placeId:'luntai',modelId:'structure',phase:0}).progress,.5);
assert.equal(cleanNavigation({version:2,stage:'event',progress:Infinity}).progress,0);
const a=cleanMemory({sessions:{zhang:{progress:.61,speed:4,mapBookmark:{...view,scene:'terrain'}},xibe:{progress:.85,speed:2}}});
assert.equal(a.sessions.zhang.progress,.61);assert.equal(a.sessions.xibe.progress,.85);assert.equal(a.sessions.protectorate,undefined);
const json=JSON.stringify({...nav,memory});assert(json.length<128*1024,'bounded real-sized records fit existing configuration import');
const extension=cleanNavigation({version:3,stage:'free',origin:{navigation:nav,workspace:view,label:'集市交换'}});
assert.equal(extension.origin.navigation.placeId,'kashgar');assert.equal(extension.origin.navigation.modelId,'market');
assert.equal(extension.origin.navigation.origin,null,'extension origins keep a single bounded return context');
assert.equal(cleanNavigation({version:3,stage:'free',origin:{navigation:nav,workspace:{...view,scene:'people'}}}).origin,null,'mismatched return context is rejected');
console.log('Exploration memory: resume context, model eligibility, backwards compatibility, deduplication and bounds passed.');
const regionView={...view,scene:'terrain'};
const withRegion={...nav,regionContext:{layer:'history',eventId:'zhang',entry:'kashgar',workspace:regionView}};
const restored=cleanNavigation(JSON.parse(JSON.stringify(withRegion)));
assert.equal(restored.regionContext.entry,'kashgar');
assert.deepEqual(restored.regionContext.workspace.camera,regionView.camera);
assert.equal(restored.regionContext.workspace.navigation,undefined);
assert.equal(cleanNavigation({...nav,regionContext:{...withRegion.regionContext,layer:'unknown'}}).regionContext,null);
assert.equal(cleanNavigation({...nav,regionContext:{...withRegion.regionContext,entry:'unknown',workspace:view}}).regionContext.entry,null);
assert.equal(cleanNavigation({...nav,regionContext:{...withRegion.regionContext,workspace:view}}).regionContext.workspace,null);
let maps=cleanMemory(null);
maps=appendObservation(maps,{version:3,stage:'region',mapLayer:'water',atlasEntry:'turpan'},regionView,'water');
maps=appendObservation(maps,{version:3,stage:'region',mapLayer:'history',atlasEntry:'kashgar'},regionView,'history');
assert.equal(maps.observations.length,2,'distinct thematic map observations retain their entries');
assert.equal(cleanNavigation(nav).regionContext,null,'old navigation needs no return context');
console.log('R39: bounded map return context and distinct thematic observations passed.');
