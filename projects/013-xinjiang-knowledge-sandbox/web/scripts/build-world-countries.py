"""Build the local globe layer from the retained Natural Earth 1:50m GeoJSON.

Requires Shapely. Originals are compressed once in R66; no runtime network fetch.
Run from the project: python web/scripts/build-world-countries.py
"""
import gzip
import hashlib
import json
from pathlib import Path
from shapely.geometry import shape, mapping

PROJECT = Path(__file__).resolve().parents[2]
SOURCE = PROJECT / 'process/round-66/source'
PUBLIC = PROJECT / 'web/public'
ALIASES = {'CHN': 'china', 'RUS': 'russia', 'MNG': 'mongolia', 'KAZ': 'kazakhstan',
           'KGZ': 'kyrgyzstan', 'TJK': 'tajikistan', 'AFG': 'afghanistan', 'PAK': 'pakistan', 'IND': 'india'}
NAMES = {'CHN': '中国', 'TWN': '台湾', 'USA': '美国', 'GBR': '英国', 'PRK': '朝鲜', 'KOR': '韩国'}

def read(name):
    raw = gzip.decompress((SOURCE / (name + '.geojson.gz')).read_bytes())
    return json.loads(raw), hashlib.sha256(raw).hexdigest()

def rounded(value):
    return [rounded(v) for v in value] if isinstance(value, (list, tuple)) else round(value, 3)

source, digest = read('ne_50m_admin_0_countries')
countries, shapes = [], {}
for feature in source['features']:
    p = feature['properties']
    code = p['ADM0_A3']
    item_id = ALIASES.get(code, 'country-' + code.lower())
    # Simplify once during preparation, never on an animation frame.
    geom = mapping(shape(feature['geometry']).simplify(.025, preserve_topology=True))
    polygons = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    shapes[item_id] = rounded(polygons)
    countries.append({'id': item_id, 'code': code, 'name': NAMES.get(code, p['NAME_ZH'] or p['NAME']),
                      'lon': 94 if code == 'RUS' else round(p['LABEL_X'], 3), 'lat': 57 if code == 'RUS' else round(p['LABEL_Y'], 3),
                      'rank': p['LABELRANK'], 'color': p['MAPCOLOR7'], 'minLabel': p['MIN_LABEL']})
land, land_digest = read('ne_50m_admin_0_boundary_lines_land')
disputed = []
for f in land['features']:
    if 'Disputed' not in f['properties']['FEATURECLA'] and 'Indefinite' not in f['properties']['FEATURECLA']:
        continue
    g = mapping(shape(f['geometry']).simplify(.015, preserve_topology=True))
    disputed.extend(rounded(g['coordinates']) if g['type'] == 'MultiLineString' else [rounded(g['coordinates'])])
encode = lambda obj: json.dumps(obj, ensure_ascii=False, separators=(',', ':'))
(PUBLIC / 'world-country-data.js').write_text('// Generated by scripts/build-world-countries.py; Natural Earth, public domain.\nexport const countryCatalog=' + encode(countries) + ';\n', encoding='utf-8')
(PUBLIC / 'world-country-shapes.js').write_text('// Natural Earth 1:50m polygons, simplified 0.025 degrees. See assets/world-countries-source.json.\nexport const countryShapes=' + encode(shapes) + ';\nexport const disputedLines=' + encode(disputed) + ';\n', encoding='utf-8')
manifest = {'edition': 'R66', 'dataset': 'Natural Earth Admin 0 countries and land boundaries, 1:50m',
            'countriesVersion': '5.1.1', 'boundariesVersion': '5.1.0', 'license': 'Public domain',
            'licenseUrl': 'https://www.naturalearthdata.com/about/terms-of-use/',
            'sourceUrl': 'https://www.naturalearthdata.com/downloads/50m-cultural-vectors/50m-admin-0-countries-2/',
            'downloadRoot': 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/',
            'retrieved': '2026-10-13', 'features': len(countries), 'sha256': digest, 'landSha256': land_digest,
            'preparation': 'Simplify polygons 0.025° with topology preserved per polygon, round to 3 decimal places; no runtime requests.',
            'scope': 'Modern country/territory geographic reference; Natural Earth default de facto geometry, not historical borders or a cadastral/official standard map. Disputed/indefinite land lines retain a dashed overlay.',
            'displayAliases': NAMES, 'labelAdjustment': 'Russia label moved to 94E 57N so its Asian extent stays labelled in the Xinjiang entry; country anchor points are labels, not capitals.'}
(PUBLIC / 'assets/world-countries-source.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
print(json.dumps({'features': len(countries), 'geometryBytes': (PUBLIC / 'world-country-shapes.js').stat().st_size, 'disputedLines': len(disputed)}))
